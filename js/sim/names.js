// Уникальное имя с fallback на римские цифры
export function uniqueName(pool, rng, used) {
  const free = pool.filter((n) => !used.has(n));
  if (free.length) { const n = rng.pick(free); used.add(n); return n; }
  const n = rng.pick(pool);
  let i = 2;
  while (used.has(`${n} ${i}`)) i++;
  const res = `${n} ${i}`;
  used.add(res);
  return res;
}
